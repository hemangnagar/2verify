/**
 * Builds a JSON document in the shape of a real NPPES NPI Registry v2.1 response
 * for a seeded person or entity. Used only as auto_api evidence in the demo; Phase 2
 * replaces this with the live call.
 */
export interface NppesSubject {
  npi: string;
  kind: "individual" | "organization";
  firstName?: string;
  lastName?: string;
  credential?: string; // "PHARMD", "MD"
  orgName?: string;
  taxonomyCode: string;
  taxonomyDesc: string;
  state: string;
  city: string;
  address: string;
  enumerationDate: string; // YYYY-MM-DD
}

export function fakeNppesResponse(s: NppesSubject, fetchedAt: Date) {
  return {
    _note: "SYNTHETIC: generated by the demo seed in the shape of https://npiregistry.cms.hhs.gov/api/?version=2.1. Not a real registry record.",
    _fetched_at: fetchedAt.toISOString(),
    result_count: 1,
    results: [
      {
        created_epoch: String(Math.floor(new Date(s.enumerationDate).getTime() / 1000)),
        enumeration_type: s.kind === "individual" ? "NPI-1" : "NPI-2",
        last_updated_epoch: String(Math.floor(fetchedAt.getTime() / 1000) - 86400 * 40),
        number: s.npi,
        addresses: [
          {
            country_code: "US",
            country_name: "United States",
            address_purpose: "LOCATION",
            address_type: "DOM",
            address_1: s.address.toUpperCase(),
            city: s.city.toUpperCase(),
            state: s.state,
            postal_code: "000000000",
            telephone_number: "000-000-0000",
          },
        ],
        basic:
          s.kind === "individual"
            ? {
                first_name: (s.firstName ?? "").toUpperCase(),
                last_name: (s.lastName ?? "").toUpperCase(),
                credential: s.credential ?? "",
                sole_proprietor: "NO",
                gender: "U",
                enumeration_date: s.enumerationDate,
                last_updated: fetchedAt.toISOString().slice(0, 10),
                status: "A",
                name_prefix: "--",
                name_suffix: "--",
              }
            : {
                organization_name: (s.orgName ?? "").toUpperCase(),
                organizational_subpart: "NO",
                enumeration_date: s.enumerationDate,
                last_updated: fetchedAt.toISOString().slice(0, 10),
                status: "A",
                authorized_official_first_name: "DEMO",
                authorized_official_last_name: "OFFICIAL",
                authorized_official_title_or_position: "PHARMACIST IN CHARGE",
              },
        taxonomies: [{ code: s.taxonomyCode, taxonomy_group: "", desc: s.taxonomyDesc, state: s.state, license: "", primary: true }],
        identifiers: [],
        endpoints: [],
        other_names: [],
        practice_locations: [],
      },
    ],
  };
}

